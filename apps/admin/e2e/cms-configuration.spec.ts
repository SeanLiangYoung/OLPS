import {expect,test} from '@playwright/test'
const apiBase=process.env.OLPS_API_URL??'http://127.0.0.1:8787'
test('外观定制预览展示已保存的颜色字体和页脚',async({page,request})=>{
  page.setDefaultTimeout(15000)
  const suffix=Date.now().toString(36)
  const registration=await request.post(`${apiBase}/api/auth/register`,{data:{account:`preview-${suffix}`,password:'Configuration123!',name:'预览测试'}})
  expect(registration.ok(),await registration.text()).toBe(true)
  const token=(await registration.json()).accessToken as string,headers={Authorization:`Bearer ${token}`}
  const creation=await request.post(`${apiBase}/api/sites`,{headers,data:{name:`外观预览 ${suffix}`}})
  expect(creation.status(),await creation.text()).toBe(201)
  const created=await creation.json(),draftId=created.draft.draftId,siteId=created.site.siteId
  await expect.poll(async()=>{const response=await request.get(`${apiBase}/api/sites/${siteId}/initialization`,{headers});const state=await response.json();if(state.initStatus==='failed')throw new Error(state.error);return state.initStatus},{timeout:90000}).toBe('ready')
  await page.addInitScript(({token,draftId,siteId})=>{if(window!==window.top)return;localStorage.setItem('olps_access_token',token);localStorage.setItem('olps_draft_id',draftId);localStorage.setItem('olps_site_id',siteId)},{token,draftId,siteId})
  await page.goto('/appearance/customize')
  const preview=page.locator('iframe[title="外观预览"]'),frame=page.frameLocator('iframe[title="外观预览"]')
  await expect(preview).toHaveAttribute('sandbox','allow-scripts allow-forms')
  await expect(frame.locator('body')).toBeVisible()
  const firstPreview=await preview.getAttribute('src')
  await page.getByLabel('主要颜色',{exact:true}).fill('#654321')
  await page.getByLabel('字体',{exact:true}).fill('Arial, sans-serif')
  await page.getByLabel('页脚文字',{exact:true}).fill('已经保存的页脚文字')
  await page.getByRole('button',{name:'保存设置',exact:true}).click()
  await expect(page.getByRole('status')).toHaveText('外观设置已保存')
  await expect(preview).not.toHaveAttribute('src',firstPreview!)
  await expect(frame.getByText('已经保存的页脚文字',{exact:true})).toBeVisible()
  await expect.poll(()=>frame.locator('html').evaluate(element=>getComputedStyle(element).getPropertyValue('--olps-color-primary').trim())).toBe('#654321')
  await expect.poll(()=>frame.locator('body').evaluate(element=>getComputedStyle(element).fontFamily)).toContain('Arial')
  const nextDraft=await request.post(`${apiBase}/api/drafts`,{headers,data:{siteId,name:'媒体切换版本'}})
  expect(nextDraft.status(),await nextDraft.text()).toBe(201)
  const nextDraftId=(await nextDraft.json()).draft.draftId as string
  await page.goto('/media')
  await page.getByLabel('上传文件',{exact:true}).setInputFiles({name:'switch.svg',mimeType:'image/svg+xml',buffer:Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="20" height="20"><rect width="20" height="20"/></svg>')})
  await expect(page.getByRole('heading',{name:'媒体详情',exact:true})).toBeVisible()
  await page.evaluate(async draftId=>{const modulePath='/src/workspaceSession.ts';const session=await import(modulePath);session.applySelectedDraftId(draftId)},nextDraftId)
  await expect(page.getByRole('heading',{name:'媒体详情',exact:true})).toHaveCount(0)
  await expect(page.getByText('没有符合条件的媒体文件。',{exact:true})).toBeVisible()
})
