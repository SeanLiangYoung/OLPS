  const reordered=page.waitForResponse(response=>response.url().endsWith('/reorder')&&response.request().method()==='POST')
  await handles.nth(0).dragTo(handles.nth(2))
  const reorderResult=await reordered
  expect(reorderResult.ok(),await reorderResult.text()).toBe(true)
