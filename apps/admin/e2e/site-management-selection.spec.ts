import { expect, test } from '@playwright/test'

const apiBase = process.env.OLPS_API_URL || 'http://127.0.0.1:8787'

test('网站入口与页面搜索选择发布保持其他页面未公开', async ({ page, request }) => {
  const suffix = Date.now().toString(36)
  const registration = await request.post(`${apiBase}/api/auth/register`, { data: { account: `managed-${suffix}`, password: 'ManagedPages123!', name: '网站管理检查' } })
  expect(registration.status()).toBe(201)
  const { accessToken } = await registration.json()
  const headers = { authorization: `Bearer ${accessToken}` }
  const created = await request.post(`${apiBase}/api/drafts`, { headers, data: { name: `管理网站 ${suffix}` } })
  expect(created.status()).toBe(201)
  const { draft } = await created.json()
  for (const [title, slug] of [['产品介绍', 'product'], ['客户案例', 'case']]) {
    expect((await request.post(`${apiBase}/api/drafts/${draft.draftId}/pages`, { headers, data: { title, slug, kind: 'site' } })).status()).toBe(201)
  }
  await page.goto('/login')
  await page.evaluate(({ token, draftId }) => { localStorage.setItem('olps_access_token', token); localStorage.setItem('olps_draft_id', draftId) }, { token: accessToken, draftId: draft.draftId })
  await page.goto('/workspace')
  await expect(page.getByRole('heading', { name: '我的网站', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '管理网站', exact: true }).click()
  await expect(page.getByRole('heading', { name: '网站概况', exact: true })).toBeVisible()
  await page.getByRole('navigation', { name: '网站管理导航' }).getByRole('link', { name: '页面管理', exact: true }).click()
  await page.getByLabel('搜索页面', { exact: true }).fill('产品')
  await expect(page.getByRole('row').filter({ hasText: '客户案例' })).toHaveCount(0)
  await page.getByRole('checkbox', { name: '选择 产品介绍', exact: true }).check()
  await page.getByRole('button', { name: '发布所选页面', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '确认发布范围' })
  await expect(dialog).toContainText('产品介绍')
  await expect(dialog).not.toContainText('客户案例')
  const completion = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith('/publication/confirm'))
  await dialog.getByRole('button', { name: '确认发布', exact: true }).click()
  const response = await completion
  expect(response.status(), await response.text()).toBe(200)
  const result = await response.json()
  await expect(page.getByRole('status').filter({ hasText: '发布成功' })).toBeVisible()
  const base = String(result.publicUrl).replace(/\/$/, '')
  expect((await request.get(`${base}/product/`)).status()).toBe(200)
  expect((await request.get(`${base}/case/`)).status()).toBe(404)
  await page.getByLabel('搜索页面', { exact: true }).fill('')
  await expect(page.getByRole('row').filter({ hasText: '产品介绍' })).toContainText('线上可访问')
  await expect(page.getByRole('row').filter({ hasText: '客户案例' })).toContainText('等待首次发布')
  await page.getByLabel('页面排序', { exact: true }).selectOption('title')
  const listed = await request.get(`${apiBase}/api/drafts/${draft.draftId}/pages`, { headers })
  const { pages } = await listed.json()
  const publishedPage = pages.find((item: { slug: string }) => item.slug === 'product')
  expect((await request.delete(`${apiBase}/api/drafts/${draft.draftId}/pages/${publishedPage.pageId}`, { headers })).status()).toBe(200)
  await page.getByRole('button', { name: '刷新', exact: true }).click()
  const productRow = page.getByRole('row').filter({ hasText: '产品介绍' })
  await expect(productRow).toContainText('等待删除')
  await productRow.getByRole('button', { name: '取消删除', exact: true }).click()
  await expect(productRow).toContainText('没有未发布更改')
  await expect(productRow.getByRole('link', { name: '编辑页面', exact: true })).toBeVisible()
  expect((await request.get(`${base}/product/`)).status()).toBe(200)
})
