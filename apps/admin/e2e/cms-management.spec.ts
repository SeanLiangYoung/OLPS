import { expect, test } from '@playwright/test'

const apiBase = process.env.OLPS_API_URL ?? 'http://127.0.0.1:8787'

test('网站创建、页面创建与媒体上传编辑替换删除', async ({ page, request }) => {
  const suffix = Date.now().toString(36)
  const registration = await request.post(`${apiBase}/api/auth/register`, { data: { account: `management-${suffix}`, password: 'Management123!', name: '管理测试' } })
  expect(registration.ok(), await registration.text()).toBe(true)
  const token = (await registration.json()).accessToken as string
  await page.addInitScript(token => localStorage.setItem('olps_access_token', token), token)
  await page.goto('/sites')
  await page.getByLabel('网站名称').fill(`管理网站 ${suffix}`)
  await page.getByRole('button', { name: '创建网站', exact: true }).click()
  await expect(page).toHaveURL(/\/dashboard$/, { timeout: 90000 })
  await expect(page.getByLabel('编辑版本',{exact:true})).toHaveValue(/[a-f\d-]{36}/)
  const originalDraft=await page.getByLabel('编辑版本',{exact:true}).inputValue()
  await page.goto('/pages')
  await page.getByRole('button', { name: '新建页面', exact: true }).click()
  await page.getByRole('dialog').getByLabel('标题', { exact: true }).fill('管理测试页面')
  await page.getByRole('dialog').getByLabel('网址名称').fill(`management-${suffix}`)
  await page.getByRole('button', { name: '创建并编辑', exact: true }).click()
  await expect(page).toHaveURL(/\/content\/page\//)
  await expect(page.getByLabel('标题', { exact: true })).toHaveValue('管理测试页面')
  await page.goto('/reports')
  await expect(page.getByRole('heading',{name:'统计与报告',exact:true})).toBeVisible()
  await expect(page.locator('.content-report').filter({hasText:'管理测试页面'})).toHaveCount(1)
  await page.goto('/media')
  const first = '<svg xmlns="http://www.w3.org/2000/svg" width="48" height="32"><rect width="48" height="32" fill="#2468ab"/></svg>'
  await page.getByLabel('上传文件', { exact: true }).setInputFiles({ name: 'management.svg', mimeType: 'image/svg+xml', buffer: Buffer.from(first) })
  await expect(page.getByRole('status')).toHaveText('媒体文件已上传')
  await expect.poll(() => page.locator('.media-preview').evaluate(image => (image as HTMLImageElement).naturalWidth)).toBe(48)
  await page.getByLabel('标题', { exact: true }).fill('管理媒体')
  await page.getByLabel('替代文本', { exact: true }).fill('蓝色矩形')
  await page.getByRole('button', { name: '保存资料', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('媒体资料已保存')
  await expect(page.getByLabel('替代文本', { exact: true })).toHaveValue('蓝色矩形')
  await page.getByLabel('替换文件', { exact: true }).setInputFiles({ name: 'replacement.svg', mimeType: 'image/svg+xml', buffer: Buffer.from(first.replace('width="48"', 'width="64"')) })
  await expect(page.getByRole('status')).toHaveText('媒体文件已替换')
  await expect.poll(() => page.locator('.media-preview').evaluate(image => (image as HTMLImageElement).naturalWidth)).toBe(64)
  await page.getByRole('button', { name: '删除媒体', exact: true }).click()
  await page.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('媒体文件已删除')
  await expect(page.getByText('没有符合条件的媒体文件。')).toBeVisible()
  await page.getByRole('button',{name:'创建编辑版本',exact:true}).click()
  await page.getByLabel('版本名称').fill('新的编辑版本')
  await page.getByRole('button',{name:'确认创建',exact:true}).click()
  await expect(page.getByLabel('编辑版本',{exact:true}).locator('option:checked')).toHaveText('新的编辑版本')
  await page.goto('/reports')
  await expect(page.locator('.content-report').filter({hasText:'管理测试页面'})).toHaveCount(0)
  await page.getByLabel('编辑版本',{exact:true}).selectOption(originalDraft)
  await expect(page.getByLabel('编辑版本',{exact:true})).toHaveValue(originalDraft)
  await page.goto('/reports')
  await expect(page.locator('.content-report').filter({hasText:'管理测试页面'})).toHaveCount(1)
})
